let modified = 0;
for (const article of newsArticles) {
  // Check if we have an expansion for this article
  let key: string | undefined;
  if (expansions[article.slug]) {
    key = article.slug;
  } else if (article.relatedAirdropId && expansions[article.relatedAirdropId]) {
    key = article.relatedAirdropId;
  }

  if (key && expansions[key]) {
    const extra = expansions[key];
    if (!article.content.includes(extra.trim().slice(0, 30))) {
      article.content = article.content.trim() + '\n' + extra;
      modified++;
      console.log(`Expanded content for: ${article.slug}`);
    }
  }
}

if (modified > 0) {
  const newsPath = path.resolve('src/data/news.ts');
  const serialized = 'export const newsArticles: NewsArticle[] = ' + JSON.stringify(newsArticles, null, 2) + ';\n';
  fs.writeFileSync(newsPath, serialized, 'utf8');
  console.log(`Successfully updated ${modified} articles in ${newsPath}!`);
} else {
  console.log('No articles needed expansion.');
}
